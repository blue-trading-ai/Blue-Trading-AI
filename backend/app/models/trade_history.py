VERSION_30_MAXIMUM_CONFIDENCE_ADJUSTMENT: Final[float] = 4.0
VERSION_30_MINIMUM_COMPLETED_TRADES: Final[int] = 20
VERSION_30_MINIMUM_SIGNAL_CONFIDENCE: Final[float] = 80.0

